    def 更新下一次刷新时间(self) -> None:
        """
        更新下次刷新时间为当前任务队列中最早刷新的子任务时间
        
        只考虑当前任务队列中的子任务，
        不在队列中的子任务即使有刷新时间也忽略
        """
        刷新情况 = self.任务状态.子任务刷新情况
        当前队列 = self.当前子任务队列
        
        if not 刷新情况 or not 当前队列:
            return
        
        有效刷新时间列表 = []
        for 队列号 in 当前队列:
            队列号_str = str(队列号)
            if 队列号_str in 刷新情况:
                有效刷新时间列表.append(刷新情况[队列号_str])
        
        if 有效刷新时间列表:
            self.任务状态.下次刷新时间 = min(有效刷新时间列表)
            调试器.trace(self.调试分类, f"更新下次刷新时间: {self.任务状态.下次刷新时间}")
        else:
            调试器.trace(self.调试分类, "当前任务队列中无有效刷新时间")

    def 更新同步子任务状态(self):
        """
        同步子任务队列和刷新情况
        
        功能：
        1. 检查 子任务队列 中的每个任务
        2. 如果任务不在 子任务刷新情况 中，则添加该任务并设置初始值为 0
        3. 返回新增的任务列表
        """
        子任务刷新情况 = self.任务状态.子任务刷新情况
        子任务队列 = self.当前子任务队列
        新增任务列表 = []
        
        for 队列号 in 子任务队列:
            队列号_str = str(队列号)
            if 队列号_str not in 子任务刷新情况:
                子任务刷新情况[队列号_str] = 0
                self.任务状态.下次刷新时间 = 0
                新增任务列表.append(队列号)
                调试器.state(self.调试分类, f"新增子任务: 队列号={队列号}, 初始刷新时间=0(立即可执行)")
        
        if 新增任务列表:
            调试器.debug(self.调试分类, f"本次同步新增 {len(新增任务列表)} 个子任务: {新增任务列表}")
        return 新增任务列表

    def 获取已刷新任务列表(self) -> List[int]:
        """
        获取所有已到刷新时间的任务队列号（考虑提前进场时间）
        
        返回:
            已到刷新时间的任务号列表（按从大到小排序）
        """
        当前时间 = time.time()
        刷新情况 = self.任务状态.子任务刷新情况
        队列列表 = self.当前子任务队列
        提前进场秒数 = self.任务配置.提前进场秒数
        
        已刷新列表 = []
        for 队列号 in 队列列表:
            队列号_str = str(队列号)
            if 队列号_str in 刷新情况:
                有效刷新时间 = 刷新情况[队列号_str] - 提前进场秒数
                if 有效刷新时间 <= 当前时间:
                    已刷新列表.append(队列号)
        
        if 已刷新列表:
            已刷新列表 = self._排序已刷新列表(已刷新列表)
            self.任务状态.下次刷新时间 = 刷新情况[str(已刷新列表[0])]
            调试器.debug(self.调试分类, f"已刷新任务: {已刷新列表}, 下次刷新时间={self.任务状态.下次刷新时间}")
        
        return 已刷新列表

    def _排序已刷新列表(self, 列表: List[int]) -> List[int]:
        """
        对已刷新列表排序（子类可覆盖）
        默认从大到小排序
        
        坐骑任务需要覆盖此方法使用专用排序
        """
        列表.sort()
        return 列表
