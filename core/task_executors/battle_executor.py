"""
通用战斗任务执行器基类

功能：
1. 通用副本战斗逻辑（目标检测、静止检测、退出条件）
2. 死亡复活处理
3. 自动战斗检测
4. 战斗状态管理
5. 目标死亡时间估算

使用方式：
    子类继承此类，实现以下方法：
    - 是否在副本中() - 判断当前是否在副本内
    - 执行入口逻辑() - 从主城进入副本的流程
    
    可选覆盖：
    - 获取退出按钮坐标() - 返回退出按钮坐标
    - 战斗结束回调() - 战斗结束后的处理
"""

import re
import time
from typing import Optional, Tuple, List
from abc import abstractmethod

from rich.repr import T

from core.utils import 匹配分组关键字, 提取次数, 解析时间文字, 读取图片, 重试,归属情况
from core.debug import 调试器
from models.task_config import 任务配置基类
from .base_executor import 任务执行器基类



class 战斗任务执行器(任务执行器基类):
    """
    通用战斗任务执行器基类
    
    提供以下通用功能：
    1. 目标检测（像素匹配）
    2. 静止检测（画面变化）
    3. 退出条件判断
    4. 自动战斗检测
    5. 死亡复活处理
    6. 目标死亡时间估算
    """
    
    def __init__(self, 线程, 任务配置, 任务状态):
        super().__init__(线程, 任务配置, 任务状态)
                
        # 加载战斗检测配置
        self._加载战斗配置()  
        self.当前子任务队列: List[int] = []   
      
    def _加载战斗配置(self):
        """加载战斗检测配置（从全局配置）"""
        战斗配置 = self.游戏配置.战斗
        
        self.目标信息区域 = self.游戏配置.目标信息区域
        self.目标存在像素规则 = 战斗配置.目标存在像素规则
        self.目标检测阈值 = 战斗配置.检测.目标检测阈值
        self.静止检测点组 = 战斗配置.检测.静止检测点组
        self.无目标超时秒数 = 战斗配置.无目标超时秒数
        self.静止超时秒数 = 战斗配置.静止超时秒数
        self.开战超时秒数 = 战斗配置.超时.开战超时秒数
        
           
    # ==================== 子类必须实现的方法 ====================
   
    @abstractmethod
    def 执行入口逻辑(self) -> bool:
        """执行从主城进入副本的流程"""
        pass
    
    # ==================== 子类可覆盖的方法 ====================
     
    def 是否在副本中(self) -> bool:
        """判断当前是否在副本中"""
        self.任务状态.是否在副本中 = self.任务配置.匹配地图(self.线程.当前地图)
        return self.任务状态.是否在副本中
 
    
    def 战斗结束回调(self):
        """战斗结束后的回调（子类可覆盖）"""
        pass
    
    # ==================== 主执行流程 ====================
    
    def 执行(self) -> str:
        """
        执行任务（模板方法）
        
        子类不应继承此方法，而是重写：
        - 是否在副本中()
        - 执行入口逻辑()
        """
        调试器.info(self.调试分类, f"开始执行: {self.任务配置.任务名称}({self.任务配置.任务ID})")
        调试器.debug(self.调试分类, f"当前地图: {self.线程.当前地图}")
        
         # 0. 检查召唤响应（副本内外均可）
        if self._检查召唤响应():            
            return "完成"


        # 1. 判断是否在副本中
        if self.是否在副本中():
            调试器.debug(self.调试分类, "判定在副本中，执行战斗逻辑")
            return self.执行副本战斗逻辑()
        
        if self.检查并处理复活():
            return "死亡"
        
        # 2. 检查前置条件
        if not self.检查前置条件():
            调试器.debug(self.调试分类, "前置条件不满足，等待中")
            return "等待"
        
        # 3. 执行入口逻辑
        调试器.debug(self.调试分类, "执行入口逻辑")
        if not self.执行入口逻辑():
             # 记录入口失败
            self.任务状态.记录入口失败()
            当前失败次数 = self.任务状态.入口连续失败次数
            冷却触发次数 = self.任务状态.入口冷却触发次数
            半程阈值 = 冷却触发次数 // 2
            
            self.通用操作.覆盖鼠标提示到边缘()
            self.通用操作.清理页面状态()  


            
            # 到达半程时执行页面清理
            if 半程阈值 > 0 and 当前失败次数 == 半程阈值:
                调试器.state(self.调试分类, f"入口连续失败{当前失败次数}次(半程)，执行页面清理")
                if self.线程.当前地图 != "盟重省":
                    调试器.debug(self.调试分类, "非主城，尝试回城")
                    self.退出副本()
            
            调试器.debug(self.调试分类, f"入口逻辑失败({当前失败次数}/{冷却触发次数})")
            
            # 检查是否已触发冷却
            if self.任务状态.下次刷新时间 > time.time():
                冷却秒数 = int(self.任务状态.下次刷新时间 - time.time())
                调试器.state(self.调试分类, f"入口连续失败{当前失败次数}次，触发冷却{冷却秒数}秒")
            
            return "失败"        
        self.通用操作.清理页面状态()
        调试器.state(self.调试分类, "已进入副本，开始战斗")
        self.任务状态.记录入口成功()
        self.任务状态.重置位置复查()
        return "进行中"
    
    # ==================== 副本战斗逻辑 ====================
    
    
    def 执行副本战斗逻辑(self) -> str:
        """
        执行副本战斗逻辑（模板方法）
        
        流程：
        1. 死亡复活 + 避让联动
        2. 更新战斗状态
        3. 位置复查（仅战斗前）
        4. 领取奖励退出
        5. 副本内检查钩子
        6. 正常阶段策略（回血）
        7. 抢怪阶段操作
        8. 退出条件检查
        9. 自动战斗/走位
        """
        调试器.debug(self.调试分类, "执行副本战斗逻辑")        
        
        # ========== 确定当前阶段 ==========
        是否抢怪 = self._是否抢怪阶段()
        启用高战避让 = self._是否启用高战避让()
        self._更新当前可用最高层数()
        # ========== 1. 死亡复活 + 避让联动 ==========
        if self.检查并处理复活(
            安全复活=not 是否抢怪,
            记录杀手=启用高战避让
        ):
            调试器.state(self.调试分类, f"死亡复活处理完成 (模式={'安全复活' if not 是否抢怪 else '原地复活'})")            
                       
            # 非抢怪阶段检查高频死亡避让
            if not 是否抢怪:
                if self._策略_高频死亡避让():
                    return "完成"            
            return "进行中"
        
        # ========== 2. 更新战斗状态 ==========      
        self._打印战斗状态()
        
        位置复查结果 = self._检查位置复查()
        if 位置复查结果 is not None:
            调试器.debug(self.调试分类, f"检查位置复查未通过：{位置复查结果}")
            return 位置复查结果

        # ========== 3. 战斗前钩子（战斗前的自定义内容） ==========
        战斗前结果=self._战斗前钩子()
        if 战斗前结果 is not None:
            调试器.debug(self.调试分类, f"战斗前钩子未通过：{战斗前结果}")
            return 战斗前结果
        
        # ========== 4. 领取奖励退出 ==========
        if self.通用操作.领取奖励退出操作():
            if self._领取奖励检查钩子() is not None:
                return "奖励领取处理完成"           
        
        # ========== 5. 副本内检查钩子 ==========
        
        结果 = self._副本内检查钩子()
        if 结果 is not None:
            return 结果
        
        # 6. 开战前避让检查
        结果 = self._开战前避让检查()
        if 结果 is not None:
            return 结果
        # ========== 6. 正常阶段策略 ==========
        if not 是否抢怪:
            if self._策略_回城回血():
                self.通用操作.点击回城石()
                return "进行中"
        
        # ========== 7. 抢怪阶段操作 ==========
        if 是否抢怪:
            self._执行抢怪操作()
        
        截图 = self.线程.截图
        self.更新目标状态()
        self.更新静止状态(截图)

        self.检查攻击模式()

        # ========== 8. 退出条件检查 ==========
        if self.检查退出条件():
            调试器.state(self.调试分类, "满足退出条件")
            if self.退出副本():
               调试器.info(self.调试分类, f"任务完成，剩余次数: {self.任务状态.剩余次数}")
            return "完成"
        
        # ========== 9. 自动战斗/走位 ==========
        if self.检查自动战斗走位前置条件():
            调试器.debug(self.调试分类, "刷新时间已到，执行自动战斗/走位")
            self.检查调整自动战斗状态()
            self.检查调整自动走位状态()
        # ============= 摇人动作 ==========        
        self._检查点击摇人按钮()

        return "进行中"
    
