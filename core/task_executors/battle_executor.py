    def _开战前避让检查古剑类副本(self) -> Optional[str]:
        """
        进副本10秒后检查是否需要避让
        
        条件：
        - 进副本超过10秒
        - 无敌人
        - 归属是外人或公会成员（不是自己）
        
        返回:
            "完成": 已退出副本
            None: 不需要避让
        """
        if not self.任务配置.开战后归属是队友且无敌人避让:
            return None
        # 只在进副本10秒后检查一次
        进本次副本时间 = time.time() - self.公共变量.地图切换时间
        if 进本次副本时间 < 10:
            return None
        
        if self.公共变量.是否有敌人:
            return None
        
        # 检查是否有敌人
        有敌人 = self.辅助识别器.敌人面板有敌人()
        if 有敌人 is not False:  # True 或 None → 不确定
            if 有敌人:  
               self.公共变量.是否有敌人= True
            return None
        
        # 无敌人 → 判定归属
        归属 = self.辅助识别器.古剑类副本归属判定()
        调试器.debug(self.调试分类, f"开战前避让检查: 无敌人，归属={归属}")
        
        #理论上是 归属情况.归属公会 才避让，但有时候识别有问题，名字识别错误。我们识别不到不避让？
        # if 归属 in (归属情况.归属外人, 归属情况.归属公会):
        if 归属 == 归属情况.归属公会:
            self.任务状态.下次刷新时间 = time.time() + 120
            self.退出副本()
            调试器.state(self.调试分类, f"开战前避让退出（归属={归属}）")
            return "完成"
        
        return None
