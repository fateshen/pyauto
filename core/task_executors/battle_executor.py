    def _更新血量记录(self, 当前血量: int, 当前时间: float = None):
        """
        更新血量记录（只记录最大和最小值）
        """
        if 当前时间 is None:
            当前时间 = time.time()
        
        # 检查是否需要重置（血量增加说明怪物已切换或回血）
        if 当前血量 > self.公共变量.记录最小血量:
            self._重置血量记录(当前血量, 当前时间)
            self.公共变量.重置抢怪参数()
            return
        
        # 更新最小值
        if 当前血量 <= self.公共变量.记录最小血量:
            self.公共变量.记录最小血量 = 当前血量
            self.公共变量.记录最小血量时间 = 当前时间
            调试器.trace(self.调试分类, f"更新最小血量: {当前血量}%")
        
        # 更新最大值
        if 当前血量 > self.公共变量.记录最大血量:
            self.公共变量.记录最大血量 = 当前血量
            self.公共变量.记录最大血量时间 = 当前时间
            调试器.trace(self.调试分类, f"更新最大血量: {当前血量}%")

  
    def 估算死亡时间(self) -> Optional[float]:
        """
        估算怪物死亡剩余时间（秒）
        
        当目标类型为怪物时正常计算并更新缓存，
        当目标类型不是怪物时返回缓存值。
        """
        # 检查目标类型
        目标类型 = self.辅助识别器.获取目标类型()
        
        if 目标类型 == "怪物":
            剩余时间 = self._计算剩余时间()
            if 剩余时间 > 0:
                self.公共变量.目标预计死亡时间 = time.time() + 剩余时间
                return 剩余时间
        
        # 非怪物或计算失败 → 使用缓存
        if self.公共变量.目标预计死亡时间 > 0:
            缓存剩余 = self.公共变量.目标预计死亡时间 - time.time()
            if 缓存剩余 > 0:
                调试器.trace(self.调试分类, f"死亡估算(缓存): 剩余{缓存剩余:.1f}秒")
                return 缓存剩余
        
        return None
    def _计算剩余时间(self) -> float:
        """
        估算怪物死亡剩余时间（秒）
      
        返回:
            预计剩余死亡时间（秒），-1表示无法估算
        """
        当前血量=self.辅助识别器.获取目标血量
        if 当前血量 is None:
            当前血量=self.公共变量.记录最小血量
        
        self._更新血量记录(当前血量)
        if self.公共变量.记录最大血量 == self.公共变量.记录最小血量:
            调试器.trace(self.调试分类, "死亡估算: 最大血量=最小血量，无法估算")
            return -1
        
        血量差 = self.公共变量.记录最大血量 - self.公共变量.记录最小血量
        原始时间差 = self.公共变量.记录最小血量时间 - self.公共变量.记录最大血量时间
        
        if 原始时间差 <= 0:
            return -1
        掉血速度 = 血量差 / 原始时间差

        if 掉血速度 <= 0:
            return -1

        if not self.任务配置.怪物有无敌:
            剩余时间 = 当前血量 / 掉血速度
            调试器.trace(self.调试分类, f"死亡估算(无无敌): 剩余{剩余时间:.1f}秒")
            return 剩余时间
        
        无敌触发血量 = self.任务配置.无敌触发血量阈值

        if 当前血量> 无敌触发血量:
            剩余时间 = 当前血量 / 掉血速度 + self.任务配置.无敌持续时间
            调试器.trace(self.调试分类, f"死亡估算(血量>无敌阈值): 剩余{剩余时间:.1f}秒")
            return 剩余时间

        无敌中,无敌已持续时间,无敌剩余时间=self._更新无敌状态(当前血量, 无敌触发血量)

        有效时间差 = 原始时间差 - 无敌已持续时间
        if 有效时间差 <= 0.1:  # 最小时间差保护
            调试器.trace(self.调试分类, f"死亡估算: 有效时间差过小({有效时间差:.2f}s)，使用原始时间差")
            有效时间差 = 原始时间差
        掉血速度 = 血量差 / 有效时间差
        
        if 掉血速度 <= 0:
            return -1
                      
        基础时间 = 当前血量 / 掉血速度
        剩余时间 = 基础时间 + 无敌剩余时间
        调试器.trace(self.调试分类, f"死亡估算(无敌修正): 基础{基础时间:.1f}s + 无敌剩余{无敌剩余时间:.1f}s = {剩余时间:.1f}秒")
        
        return 剩余时间



