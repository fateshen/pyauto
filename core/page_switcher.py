# ==================== 点击图片切换 ====================

class 点击图片切换(切换操作基类):
    """点击图片切换页面 - 找图后点击"""
    
    def _执行点击(self) -> bool:
        点击配置 = self.点击配置
        区域 = 点击配置.get("区域")
        图片路径 = 点击配置.get("图片路径")
        相似度 = 点击配置.get("相似度", 0.8)
        缩放比例 = 点击配置.get("缩放比例", 0.5)
        刷新 = 点击配置.get("刷新", True)
        按键 = 点击配置.get("按键", "left")
        偏移 = 点击配置.get("偏移")  # 新增：偏移属性 (left, top, right, bottom)
        原区域缩放= 点击配置.get("原区域缩放")
        if not 区域 or not 图片路径:
            调试器.warning("页面切换", "缺少区域或图片路径")
            return False
        
        # 使用读取图片函数加载图片
        模板 = 读取图片(图片路径)
        if 模板 is None:
            调试器.warning("页面切换", f"图片加载失败: {图片路径}")
            return False
        
        # 刷新截图
        if 刷新:
            截图 = self.线程.刷新截图()
        else:
            截图 = self.线程.截图        
        if 截图 is None:
            调试器.debug("页面切换", "截图失败")
            return False
        
        # 找图
        匹配器 = self.线程.模板匹配器
        结果 = 匹配器.match(截图, 模板, threshold=相似度, region=区域)
        
        if not 结果:
            调试器.debug("页面切换", f"未找到图片 '{图片路径}' (相似度={相似度})")
            return False
        
        # 获取匹配到的图片区域
        点击区域 = (结果.left, 结果.top, 结果.right, 结果.bottom)
        
        # 如果有偏移配置，则应用偏移
        if 偏移 and len(偏移) == 4:
            原区域 = 点击区域
            # 偏移格式：(偏移左, 偏移上, 偏移右, 偏移下)
            左偏移, 上偏移, 右偏移, 下偏移 = 偏移
            
            # 以匹配到的左上角为基准，加上偏移量
            新区域左 = 结果.left + 左偏移
            新区域上 = 结果.top + 上偏移
            新区域右 = 结果.left + 右偏移   # 注意：这里基于左上角
            新区域下 = 结果.top + 下偏移
            
            点击区域 = (新区域左, 新区域上, 新区域右, 新区域下)
            
            调试器.debug("页面切换", f"应用偏移: 原区域={原区域} -> 新区域={点击区域}")
        if 原区域缩放:
            if isinstance(原区域缩放, (int, float)):
                点击区域 = 区域
                缩放比例=原区域缩放
       
        return self._点击随机点(点击区域, 缩放比例,按键)


# ==================== 点击文字切换 ====================

class 点击文字切换(切换操作基类):
    """点击文字切换页面 - 找字后点击"""
    
    def _执行点击(self) -> bool:
        点击配置 = self.点击配置
        区域 = 点击配置.get("区域")
        关键字 = 点击配置.get("关键字")
        完全匹配 = 点击配置.get("完全匹配", False)
        缩放比例 = self.点击配置.get("缩放比例", 0.5)
        刷新 = 点击配置.get("刷新", True)
        if not 区域 or not 关键字:
            调试器.warning("页面切换", "缺少区域或关键字")
            return False
        
        # 刷新截图
        if 刷新:
            截图 = self.线程.刷新截图()
        else:
            截图 = self.线程.截图        
        if 截图 is None:
            调试器.debug("页面切换", "截图失败")
            return False
        
        # 识别文字位置
        识别器 = self.线程.文字识别器
        结果 = 识别器.recognize_result(截图, 区域)
        if not 结果:
            调试器.debug("页面切换", f"区域 {区域} 未识别到文字")
            return False
        
        # 查找匹配的文字
        匹配类型 = "exact" if 完全匹配 else "group"
        目标位置 = 结果.find(关键字, match_type=匹配类型)
        
        if not 目标位置:
            调试器.debug("页面切换", f"未找到关键字 '{关键字}' (匹配类型={匹配类型})")
            return False
        
        # 获取文字区域并在区域内随机点击
        return self._点击随机点(目标位置, 缩放比例)


# ==================== 切换操作工厂 ====================

class 切换操作工厂:
    """切换操作工厂，根据配置创建切换操作实例"""
    
    @staticmethod
    def 创建(线程, 操作配置: dict) -> 切换操作基类:
        """
        根据配置创建切换操作
        
        操作配置格式:
        {
            "点击类型": "点击文字" / "点击图片" / "点击坐标" / "点击区域",
            "点击配置": {...},
            "验证配置": {...},
            "重试配置": {...}
        }
        """
        点击类型 = 操作配置.get("点击类型")
        点击配置 = 操作配置.get("点击配置", {})
        验证配置 = 操作配置.get("验证配置", {})
        重试配置 = 操作配置.get("重试配置", {})        

        if 点击类型 == 点击类型枚举.点击文字:
            return 点击文字切换(线程, 点击配置, 验证配置, 重试配置)
        elif 点击类型 == 点击类型枚举.点击图片:
            return 点击图片切换(线程, 点击配置, 验证配置, 重试配置)
        elif 点击类型 == 点击类型枚举.点击坐标:
            return 点击坐标切换(线程, 点击配置, 验证配置, 重试配置)
        elif 点击类型 == 点击类型枚举.点击区域:
            return 点击区域切换(线程, 点击配置, 验证配置, 重试配置)
        else:
            raise ValueError(f"未知点击类型: {点击类型}")


