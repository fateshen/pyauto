class 验证类型枚举(str, Enum):
    """验证类型枚举"""
    文字存在 = "文字存在"
    文字消失 = "文字消失"
    图片存在 = "图片存在"
    图片消失 = "图片消失"


class 点击类型枚举(str, Enum):
    """点击类型枚举"""
    点击文字 = "点击文字"
    点击图片 = "点击图片"
    点击坐标 = "点击坐标"
    点击区域 = "点击区域"


# ==================== 切换操作基类 ====================

class 切换操作基类:
    """
    页面切换操作基类
    
    流程：
    1. 先校准（如果启用，检查是否已在目标页面）
    2. 循环重试：执行点击 → 等待 → 验证
    """
    
    def __init__(self, 线程, 点击配置: dict, 验证配置: dict, 重试配置: dict = None):
        """
        初始化切换操作
        
        参数:
            线程: 窗口线程实例（持有全局变量）
            点击配置: 点击相关配置
            验证配置: 验证相关配置
            重试配置: 重试相关配置
        """
        self.线程 = 线程
        self.点击配置 = 点击配置
        self.验证配置 = 验证配置
        
        # 重试配置默认值
        self.重试配置 = {
            "最大重试次数": 2,
            "重试延迟": 300  # 毫秒
        }
        if 重试配置:
            self.重试配置.update(重试配置)
    
    def 执行(self) -> bool:
        """
        执行切换操作
        
        返回:
            True: 切换成功
            False: 切换失败
        """
        # 1. 先校准（如果启用）
        if self.验证配置.get("先验证", False):
            if self._先校准():
                调试器.debug("页面切换", "已在目标页面，无需切换")
                return True
        else:
            调试器.trace("页面切换", "跳过先验证")
        
        # 2. 循环重试
        最大重试次数 = self.重试配置.get("最大重试次数", 3)
        
        for 尝试次数 in range(最大重试次数):
            调试器.debug("页面切换", f"第 {尝试次数 + 1}/{最大重试次数} 次尝试")
            
            # 执行点击
            if not self._执行点击():
                调试器.debug("页面切换", f"第 {尝试次数 + 1} 次点击失败")
                continue
            
            # 等待
            self._等待(尝试次数)
            
            # 刷新截图并验证
            if self._验证():
                调试器.debug("页面切换", "验证成功")
                return True
            else:
                调试器.debug("页面切换", f"第 {尝试次数 + 1} 次验证失败")
        
        # 所有重试都失败
        调试器.warning("页面切换", f"所有 {最大重试次数} 次重试均失败")
        return False
    
    def _先校准(self) -> bool:
        """先校准：检查是否已在目标页面（使用当前缓存截图）"""
        if not self.验证配置:
            return False
        
        截图 = self.线程.截图
        if 截图 is None:
            return False
        
        return self._执行验证(截图)
    
    def _验证(self) -> bool:
        """验证：刷新截图后验证（支持重试）"""
        if not self.验证配置:
            调试器.trace("页面切换", "无验证配置，默认成功")
            return True
        
        验证重试次数 = self.重试配置.get("最大重试次数", 3)
        
        for 验证尝试 in range(验证重试次数):
            # 刷新截图
            截图 = self.线程.刷新截图()
            if 截图 is None:
                调试器.debug("页面切换", "验证时截图失败")
                if 验证尝试 < 验证重试次数 - 1:
                    self._等待(验证尝试)
                continue
            
            if self._执行验证(截图):
                return True
            
            if 验证尝试 < 验证重试次数 - 1:
                调试器.debug("页面切换", f"验证第 {验证尝试 + 1} 次失败，准备重试")
                self._等待(验证尝试)
        
        return False
    
    def _执行验证(self, 截图) -> bool:
        """执行验证逻辑"""
        验证类型 = self.验证配置.get("验证类型")
        区域 = self.验证配置.get("区域")
        验证内容 = self.验证配置.get("验证内容")
        
        识别器 = self.线程.文字识别器
        匹配器 = self.线程.模板匹配器
        
        if 验证类型 == 验证类型枚举.文字存在:
            return self._验证文字存在(识别器, 区域, 验证内容, 截图)
        elif 验证类型 == 验证类型枚举.文字消失:
            return not self._验证文字存在(识别器, 区域, 验证内容, 截图)
        elif 验证类型 == 验证类型枚举.图片存在:
            return self._验证图片存在(匹配器, 区域, 验证内容, 截图)
        elif 验证类型 == 验证类型枚举.图片消失:
            return not self._验证图片存在(匹配器, 区域, 验证内容, 截图)
        
        调试器.warning("页面切换", f"未知验证类型: {验证类型}")
        return False
    
    def _验证文字存在(self, 识别器, 区域, 文字, 截图) -> bool:
        """验证指定区域是否存在指定文字"""
        if not 区域 or not 文字:
            return False
        
        结果 = 识别器.recognize_text(截图, 区域)
        存在 = 匹配分组关键字(结果, 文字)
        调试器.trace("页面切换", f"文字验证 规则'{文字}' 识别'{结果}' -> {'匹配' if 存在 else '未匹配'}")
        return 存在
    
    def _验证图片存在(self, 匹配器, 区域, 图片路径, 截图) -> bool:
        """验证指定区域是否存在指定图片"""
        if not 区域 or not 图片路径:
            return False
        
        # 使用读取图片函数加载图片
        模板 = 读取图片(图片路径)
        if 模板 is None:
            调试器.warning("页面切换", f"图片加载失败: {图片路径}")
            return False
        
        结果 = 匹配器.match(截图, 模板, threshold=0.8, region=区域)
        存在 = 结果 is not None
        调试器.trace("页面切换", f"图片验证 '{图片路径}' -> {'找到' if 存在 else '未找到'}")
        return 存在
    
    def _等待(self, 尝试次数: int = 0):
        """
        等待延迟
        
        参数:
            尝试次数: 当前尝试次数（用于递增延迟）
        """
        延迟配置 = self.重试配置.get("重试延迟", 300)
        
        # 支持递增延迟
        if isinstance(延迟配置, (int, float)):
            基准延迟 = 延迟配置
            偏移 = 基准延迟 * 0.2  # 20% 随机偏移
        elif isinstance(延迟配置, list) and len(延迟配置) >= 2:
            基准延迟, 偏移 = 延迟配置[0], 延迟配置[1]
        else:
            基准延迟 = 300
            偏移 = 50
        
        # 递增延迟：每次重试增加 50%
        实际延迟 = 基准延迟 * (1 + 尝试次数 * 0.5)
        
        # 添加随机偏移
        延迟 = random.randint(int(实际延迟 - 偏移), int(实际延迟 + 偏移))
        延迟 = max(100, 延迟)  # 最小100毫秒
        
        调试器.trace("页面切换", f"等待 {延迟}ms")
        time.sleep(延迟 / 1000)
    
    def _执行点击(self) -> bool:
        """执行点击操作（子类实现）"""
        raise NotImplementedError
    
    def _点击随机点(self, 区域, 缩放比例: float = 0.5,button:str="left") -> bool:
        """
        在区域内点击随机点
        
        参数:
            区域: 区域坐标元组 (左, 上, 右, 下)
            缩放比例: 随机点范围缩放比例，默认0.5表示在50%中心区域内随机
        
        返回:
            True: 点击成功
        """
        if not 区域:
            调试器.warning("页面切换", "缺少区域")
            return False
        
        随机点坐标 = 随机点(区域, 缩放比例)
        self.线程.动作执行器.click(随机点坐标[0], 随机点坐标[1],button)
        调试器.trace("页面切换", f"区域随机点{button}点击 ({随机点坐标[0]}, {随机点坐标[1]})")
        return True


