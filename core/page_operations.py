class 页面操作:
    """
    单个页面操作封装
    
    支持两种调用方式：
        操作.执行()           # 直接执行
        操作()                # 可调用对象
    """
    
    def __init__(self, 操作实例):
        self._操作 = 操作实例
    
    def 执行(self) -> bool:
        """执行操作"""
        return self._操作.执行()
    
    def __call__(self) -> bool:
        """支持直接调用"""
        return self.执行()


