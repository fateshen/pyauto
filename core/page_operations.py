    # ==================== 批量执行 ====================
    
    def 执行步骤列表(self, 步骤列表: List[页面操作]) -> bool:
        """
        批量执行步骤
        
        参数:
            步骤列表: [操作1, 操作2, ...]
        
        返回:
            True: 所有步骤成功
        """
        for i, 步骤 in enumerate(步骤列表):
            调试器.debug("页面操作", f"批量执行步骤 {i + 1}/{len(步骤列表)}")
            if not 步骤.执行():
                调试器.warning("页面操作", f"批量执行步骤 {i + 1} 失败")
                return False
        return True
    
