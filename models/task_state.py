# models/task_state.py
"""
任务状态模块 - 定义任务状态基类和具体任务状态

功能：
1. 任务状态基类（包含剩余次数、刷新时间等通用状态）
2. 具体任务状态（暗殿状态、BOSS状态等）

依赖：pydantic
"""
from pydantic import BaseModel, Field
from typing import Optional
import time

class 任务状态基类(BaseModel):
    """
    任务状态基类 - 所有任务状态的基类
    
    存储任务的运行时状态，每个任务实例独立
    """
    
    # 今日已完成次数
    今日已完成次数: int = 0
    
    # 剩余次数
    剩余次数: int = 3
    
    # 下次刷新时间（时间戳，0表示未设置）
    下次刷新时间: float = 0
    
    # 是否在副本中
    是否在副本中: bool = False
    
     # ========== 上次摇人时间 ==========
    上次点击摇人按钮时间: float = 0

    # ========== 入口失败冷却 ==========
    # 入口逻辑连续失败次数
    入口连续失败次数: int = 0
    
    # 触发冷却的失败次数阈值
    入口冷却触发次数: int = 5
    
    # 每次冷却的基础秒数（递增倍数）
    入口冷却基础秒数: int = 180
    
    # ========== 进入后复查当前位置 ==========
    上次位置复查时间: float = 0
    位置复查次数: int = 0

    # 上次次数刷新时间戳
    上次次数刷新时间: float = 0.0   

    class Config:
        arbitrary_types_allowed = True
    
    def 重置位置复查(self):
        """重置位置复查状态（每次进本时调用）"""
        self.上次位置复查时间 = 0.0
        self.位置复查次数 = 0
    def 记录入口失败(self):
        """记录入口失败，达到阈值后自动设置冷却"""
        
        self.入口连续失败次数 += 1
        
        if self.入口连续失败次数 >= self.入口冷却触发次数:
            # 设置冷却：基础秒数 × 失败次数 / 触发次数
            冷却秒数 = self.入口冷却基础秒数 * (self.入口连续失败次数 // self.入口冷却触发次数)
            self.下次刷新时间 = time.time() + 冷却秒数
    
    def 记录入口成功(self):
        """入口成功后重置失败计数"""
        self.入口连续失败次数 = 0
    def 重置(self):
        """重置状态（用于任务重新开始）"""
        self.今日已完成次数 = 0
        self.剩余次数 = self.剩余次数  # 保持原值
        self.下次刷新时间 = 0
        self.是否在副本中 = False
        self.入口连续失败次数 = 0
    
    def 完成一次(self):
        """完成一次任务"""
        if self.剩余次数 > 0:
            self.剩余次数 -= 1
            self.今日已完成次数 += 1
    
    def 设置刷新时间(self, 时间戳: float):
        """设置下次刷新时间"""
        self.下次刷新时间 = 时间戳
    
    def 是否需要刷新(self, 当前时间戳: float) -> bool:
        """判断是否需要刷新（如果设置了刷新时间且已到）"""
        if self.下次刷新时间 <= 0:
            return False
        return 当前时间戳 >= self.下次刷新时间
    
    def 获取状态信息(self) -> dict:
        """获取状态信息（用于调试）"""
        return {
            "今日已完成次数": self.今日已完成次数,
            "剩余次数": self.剩余次数,
            "下次刷新时间": self.下次刷新时间,
            "是否在副本中": self.是否在副本中
        }


