# models/task_config.py
"""
任务配置模块 - 定义任务配置基类和具体任务配置
"""
from pydantic import BaseModel, Field
from typing import Optional, List, Tuple
from enum import Enum


class 召唤响应优先级模式(str, Enum):
    高优先级 = "高优先级"
    仅普通任务 = "仅普通任务"

class 召唤响应完成模式(str, Enum):
    不限制 = "不限制"
    已完成才响应 = "已完成才响应"
    未完成才响应 = "未完成才响应"


class 任务配置基类(BaseModel):
    """
    任务配置基类 - 所有任务配置的基类
    """
    
    # 基础属性
    任务ID: str = ""
    任务名称: str = ""
    任务类型: str="小时任务"  # 任务类型 小时任务/每日任务/定时任务/活动任务/特殊任务
    优先级: int = 2
    是否启用: bool = True
    
    # 时间属性
    工作时间开始: int = 0
    工作时间结束: int = 24
        
    # 地图关键字
    地图关键字: str = ""
    
    # 次数属性   
    提前进场秒数: int = 0
    大于此数量才启动任务: int = 1
    


    #自动战斗走位
    启用自动战斗: Optional[bool] = None
    启用自动走位: Optional[bool] = None

     # ========== 战斗策略 ========== 
    避让模式使用全局设置: bool=False 
    启用高战避让模式: bool=False             # 是否启用避让模式
    启用高频死亡避让模式: bool=False
    避让杀手名单: str=""                # 用|分隔的杀手名字
    高频死亡避让秒数: int =60            # 倒数第3次死亡距今 < N秒触发避让
    高频死亡避让次数: int = 3
    避让冷却秒数: int =180                # 避让后冷却秒数

    开战后归属是队友且无敌人避让: bool=False
    
    回城回血使用全局设置: bool=False 
    启用回城回血: bool=False              # 是否启用低血量回城
    回城血量阈值: int =30                 # 血量低于此百分比触发回城
    
    启用抢怪模式: bool=False              # 是否启用抢怪模式
    死亡前多少秒抢归属: int =15             # 预计死亡时间 < N秒触发抢怪
    低于此血量抢怪: int = 3
    # ========== 启用摇人按钮 ==========
    启用摇人按钮: bool = False    

     # ========== 召唤响应配置 ==========
    启用响应召唤: bool = False
    召唤响应优先级模式: str = "仅普通任务" # 高优先级/仅普通任务
    召唤启用任务完成状况动态管理: bool = False # 为True 才会启动下面层级管理，
    召唤_任务完成后响应所有层级: bool = False
    召唤_未完成任务响应当前层级: bool = False

     # ========== 攻击模式 ==========
    默认攻击模式: str = ""  # 空=使用全局配置

    #=================== 开发配置，不需要玩家自定义==================
    当前任务可执行的最高层数: int = 0
    # 调试模式（开启后该任务执行时日志级别提升到 VERBOSE）
    调试模式: bool = False
    调试分类: str = ""

        # 战斗死亡时间估算配置
    怪物有无敌: bool = False           # 怪物是否有无敌阶段
    无敌触发血量阈值: int = 20      # 无敌触发血量阈值（20%）
    无敌持续时间: int = 20             # 无敌持续时间（秒）    
    
    # 位置复查
    启用位置复查: bool = False
    位置复查目标中心: str = ""       # 格式: "x,y"
    位置复查目标半径: int = 10
    位置复查触发秒数: int = 5        # 离刷新 > N秒才复查
    位置复查移动区域: str = ""       # 格式: "x1,y1,x2,y2"

    # ========== 执行时间窗口 ==========
    # 多段时间段，"11:15-11:45,16-17,21:00-22"
    # 为空则使用 工作时间开始/结束
    工作时间段列表: str = ""

    # ========== 执行日期规则 ==========
    # "" = 每天
    # "星期1,3,5"           指定星期
    # "日期单数日"/"日期双数日"
    # "日期1,3,5,7,9"       指定日期
    # "日期8-27"            日期范围
    # "除星期6"             排除星期
    # & 连接表示"且"： "星期1-5 & 日期单数日"
    执行日期规则: str = ""

    # ========== 次数刷新 ==========
    次数刷新间隔小时: float = 0         # 暗殿=2，神兵=1
    次数刷新区间列表: str = ""          # "10:59-11:03,15:59-16:03"
    次数刷新区间条件: str = ""          # 与区间一一对应，用|分隔
    
    # 解析后的地图关键字组
    地图关键字组列表: List[List[str]] = Field(default_factory=list)
    
    class Config:
        arbitrary_types_allowed = True
    
    def __init__(self, **data):
        super().__init__(**data)
        if self.地图关键字:
            self.地图关键字组列表 = self._解析地图关键字(self.地图关键字)
   
    def _解析地图关键字(self, 关键字字符串: str) -> List[List[str]]:
        """解析地图关键字"""
        if not 关键字字符串:
            return []
        
        组列表 = []
        for 组 in 关键字字符串.split('|'):
            组 = 组.strip()
            if 组:
                关键字列表 = [k.strip() for k in 组.split(',') if k.strip()]
                if 关键字列表:
                    组列表.append(关键字列表)
        
        return 组列表
    
    def 匹配地图(self, 地图名称: str) -> bool:
        """
        检查地图名称是否匹配该任务
        
        规则：至少有一组关键字全部在地图名称中
        - 组内用逗号分隔：需要同时包含所有关键字（AND关系）
        - 组间用竖线分隔：任意一组匹配即可（OR关系）
        
        示例：
            "暗殿"                    -> 地图名包含"暗殿"即可
            "跨服战场,战场"           -> 地图名必须同时包含"跨服战场"和"战场"
            "暗殿|跨服战场,战场"       -> 包含"暗殿" 或 同时包含"跨服战场"和"战场"
        """
        if not 地图名称:
            return False
        
        if not self.地图关键字组列表:
            return False
        
        for 关键字组 in self.地图关键字组列表:
            if all(关键字 in 地图名称 for 关键字 in 关键字组):
                return True
        
        return False
    
    def 是否在工作时间内(self, 当前小时: int) -> bool:
        """检查当前时间是否在工作时间内"""
        if self.工作时间开始 == 0 and self.工作时间结束 == 24:
            return True
        
        if self.工作时间开始 < self.工作时间结束:
            return self.工作时间开始 <= 当前小时 < self.工作时间结束
        
        当前小时_调整 = 当前小时 + 24 if 当前小时 < self.工作时间开始 else 当前小时
        结束_调整 = self.工作时间结束 + 24 if self.工作时间结束 < self.工作时间开始 else self.工作时间结束
        
        return self.工作时间开始 <= 当前小时_调整 < 结束_调整
    
    def 获取任务信息(self) -> dict:
        """获取任务基本信息"""
        return {
            "任务ID": self.任务ID,
            "任务名称": self.任务名称,
            "任务类型": self.任务类型,
            "优先级": self.优先级,
            "是否启用": self.是否启用,
            "工作时间": f"{self.工作时间开始}:00-{self.工作时间结束}:00",
            "地图关键字": self.地图关键字,
            "地图关键字组": self.地图关键字组列表,
            "每日次数": self.每日次数,
            "提前进场秒数": self.提前进场秒数
        }

