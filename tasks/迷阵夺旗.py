    def 执行副本战斗逻辑(self) -> str:
        """
        执行副本战斗逻辑（模板方法）
        
        流程：
        1. 死亡复活 + 避让联动
        2. 更新战斗状态
        3. 位置复查（仅战斗前）
        4. 领取奖励退出
        5. 副本内检查钩子
        6. 正常阶段策略（回血）
        7. 抢怪阶段操作
        8. 退出条件检查
        9. 自动战斗/走位
        """
        调试器.debug(self.调试分类, "执行副本战斗逻辑")        
        
      
        # ========== 1. 死亡等待 ==========
        for _ in range(5):
            if self.辅助识别器.查找图片单结果(self.游戏配置.区域.至尊联赛.迷阵夺旗死亡问号校正区域.元组,"迷阵夺旗问号校正.bmp"):
                break
            time.sleep(1)
            self.线程.刷新截图()
        
        # ========== 2. 更新战斗状态 ==========  
        敌人= self.辅助识别器.敌人面板有敌人()
        调试器.debug(self.调试分类, f"更新战斗状态：有敌人={bool(敌人)}")
        if not self.辅助识别器.敌人面板有敌人():   
            调试器.debug(self.调试分类, "等待敌人出现")
            位置复查结果 = self._检查位置复查()
            if 位置复查结果 is not None:
                调试器.debug(self.调试分类, f"检查位置复查未通过：{位置复查结果}")
                return 位置复查结果

        
        
        # ========== 4. 领取奖励退出 ==========
        if self.通用操作.领取奖励退出操作():
            if self._领取奖励检查钩子() is not None:
                return "奖励领取处理完成"           
        
        # ========== 5. 副本内检查钩子 ==========     
        
        截图 = self.线程.截图
        self.更新目标状态()
        self.更新静止状态(截图)
       
        # ========== 8. 退出条件检查 ==========
        # if self.检查退出条件():
        #     调试器.state(self.调试分类, "满足退出条件")
        #     if self.退出副本():
        #        调试器.info(self.调试分类, f"任务完成，剩余次数: {self.任务状态.剩余次数}")
        #     return "完成"
        
        # ========== 9. 自动战斗/走位 ==========
        if self.检查自动战斗走位前置条件():
            调试器.debug(self.调试分类, "刷新时间已到，执行自动战斗/走位")
            self.检查调整自动战斗状态()
            self.检查调整自动走位状态()
       

        return "进行中"
    


    def _检查位置复查(self) -> Optional[str]:
        """
        检查并调整角色位置到当前子任务boss坐标

        返回:
            None: 已在范围内，不需要复查
            "移动中": 正在移动或已触发移动
            "无新任务，退出副本": 没有可处理的子任务
        """
        旗子=self.任务配置.目标旗子
       
        # ========== 2. 获取boss坐标 ==========
        boss坐标 = self.BOSS坐标.get(旗子)
        if boss坐标 is None:
            调试器.warning(self.调试分类, f"位置复查: 未找到子任务{旗子}的boss坐标")
            return None

        目标x, 目标y = boss坐标

        # ========== 3. 获取当前坐标 ==========
        当前坐标 = self.辅助识别器.获取当前玩家坐标()
        if 当前坐标 is None:
            调试器.debug(self.调试分类, "位置复查: 无法获取当前坐标")
            return None

        当前x, 当前y = 当前坐标
        距离 = ((当前x - 目标x) ** 2 + (当前y - 目标y) ** 2) ** 0.5

        # ========== 4. 判断是否在范围内 ==========
        if 距离 <= self.任务配置.位置复查目标半径:
            调试器.trace(
                self.调试分类,
                f"位置复查: 已在范围内(距离{距离:.0f}≤{self.任务配置.位置复查目标半径})",
            )
            self.任务状态.移动开始时间 = 0.0            
            return None

        

        # ========== 6. 不在范围内，判断是否需要移动 ==========
        静止时长 = self.公共变量.获取静止时长()
        移动已耗时 = (
            time.time() - self.任务状态.移动开始时间
            if self.任务状态.移动开始时间 > 0
            else 0
        )
        需要移动 = False

        # 移动超时保护
        if self.任务状态.移动开始时间 > 0 and 移动已耗时 > 15:
            调试器.warning(
                self.调试分类,
                f"位置复查: 移动超时({移动已耗时:.0f}秒>15秒)，重新移动",
            )
            self.任务状态.移动开始时间 = 0.0
            需要移动 = True

        # 画面静止 → 卡住了或到达了但识别不准，重新移动
        if 静止时长 > self.静止超时秒数:
            调试器.state(
                self.调试分类,
                f"位置复查: 画面静止{静止时长:.1f}秒，移动到({目标x},{目标y})",
            )
            需要移动 = True

        if 需要移动:
            移动目标区域按钮 = getattr(
                self.游戏配置.区域.至尊联赛,
                f"迷阵夺旗按钮{旗子}",
                None,
                )
            if 移动目标区域按钮:
                self.通用操作.点击区域(移动目标区域按钮.元组,2)
                self.任务状态.移动开始时间 = time.time()

        # 画面还在变化 → 正在移动中
        调试器.trace(
            self.调试分类,
            f"位置复查: 移动中(静止{静止时长:.1f}秒，距离{距离:.0f}，已耗时{移动已耗时:.0f}秒)",
        )

        return "移动中"