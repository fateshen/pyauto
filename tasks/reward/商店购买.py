    def _尝试购买货物(self, 货物区域列表, 货物名称: str, 货物配置: dict) -> bool:
        """尝试购买单个货物，返回是否成功购买"""
        if not 货物配置["是否购买"]:
            调试器.trace("商店购买", f"{货物名称}: 未启用购买")
            return False
        # if 是否为今天(货物配置["购买完成时间"]):
        #     调试器.trace("商店购买", f"{货物名称}: 今天已购买")
        #     return False

        标题区域集合 = 货物区域列表.find(货物配置["关键词"], return_all=True)
        if not 标题区域集合:
            调试器.trace("商店购买", f"{货物名称}: 未找到 '{货物配置['关键词']}'")
            return False

        核对价格 = 货物配置.get("核对价格", 0)
        调试器.trace("商店购买", f"{货物名称}: 找到 {len(标题区域集合)} 个匹配, 核对价格={核对价格}")
        已购买= False
        for idx, 标题区域 in enumerate(标题区域集合):
            信息区域 = 创建货物信息区域(标题区域)
            if 信息区域 is None:
                调试器.trace("商店购买", f"{货物名称}[{idx}]: 无法创建信息区域, x={标题区域[0]}")
                continue

            信息文字=self.辅助识别器.获取区域文字(信息区域)
            调试器.trace("商店购买", f"{货物名称}[{idx}]: 信息文字:{信息文字}")
            if 匹配分组关键字(信息文字, "售|罄"):
                调试器.info("商店购买", f"{货物名称}[{idx}]: 已售罄, 标记完成")
                货物配置["购买完成时间"] = time.time()
                continue
            红字 = self.辅助识别器.获取区域文字(信息区域, {
                "color_range": "80,255,0,20,0,20",
                "keep_color": True,
                "background": "black",
            })
            调试器.trace("商店购买", f"{货物名称}[{idx}]: 找到红字：{红字}")
            
            if 提取次数(红字) > 0:
                调试器.trace("商店购买", f"{货物名称}[{idx}]: 红字次数不足, 跳过")
                continue
            
            绿字 = self.辅助识别器.获取区域文字(信息区域, {
                "color_range": "20,50,150,255,0,16",
                "keep_color": True,
                "background": "black",
            })
            绿字次数 = 提取次数(绿字)
         
            调试器.trace("商店购买", f"{货物名称}[{idx}]: 绿字={绿字}: 绿字次数={绿字次数}")
            
            if 绿字次数 <= 0:
                调试器.trace("商店购买", f"{货物名称}[{idx}]: 无绿字, 跳过")
                continue

            if 核对价格 != 0 and 绿字次数 != 核对价格:
                调试器.trace("商店购买", f"{货物名称}[{idx}]: 价格不匹配 (绿字={绿字次数}, 核对={核对价格}), 跳过")
                continue

            调试器.info("商店购买", f"{货物名称}[{idx}]: 满足条件, 尝试购买")
            self.通用操作.点击区域(信息区域, 2)
            if self._购买操作(MAX=True):
                货物配置["购买完成时间"] = time.time()
                调试器.info("商店购买", f"{货物名称}[{idx}]: 购买成功")
                已购买= True
            else:
                调试器.warning("商店购买", f"{货物名称}[{idx}]: 购买操作失败")

        return 已购买