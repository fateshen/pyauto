def 创建货物信息区域(标题区域: Tuple[int, int, int, int]) -> Optional[Tuple[int, int, int, int]]:
        """
        根据 x 坐标创建区域四元组 (left, top, right, bottom)
        
        参数:
            x: 输入的 x 坐标
        
        返回:
            如果 x 在某个区间内，返回 (left, x+20, right, x+110)
            否则返回 None
        """
        # 定义三组区间 (left, right)
        区间列表 = [
            (557, 708),
            (805, 951),
            (1046, 1197),        ]
        
        for left, right in 区间列表:
            if left-67 <= 标题区域[0] <= right:
                return (left, 标题区域[1] + 20, right, 标题区域[1] + 110)        
        return None
