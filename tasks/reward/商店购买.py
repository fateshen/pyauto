    def 是否需要购买(self) -> bool:
        """检查是否还有需要购买的货物"""
        for 标签配置 in self.商店购买配置.values():
            for 货物配置 in 标签配置["货物"].values():
                if 货物配置["是否购买"] and not 是否为今天(货物配置["购买完成时间"]):
                    return True
        return False
    def _执行商店购买(self) -> bool:
        """商店主流程"""
        # 购买结果 = {}
        是否产生购买=False
        已处理标签 = set()
        最大商店标签页数 = 2

        商店标签 = self.辅助识别器.获取区域文字坐标(self.配置.区域.商店.商店标题按钮区域标签.元组)
        if 商店标签 is None:
            return 是否产生购买

        for _ in range(最大商店标签页数):
            for 标签名称, 标签配置 in self.商店购买配置.items():
                if 标签名称 in 已处理标签:
                    continue
                
                # if 标签名称 not in 购买结果:
                #     购买结果[标签名称] = {}
                
                if not self._进入商店标签页(商店标签, 标签配置):
                    continue
                
                已处理标签.add(标签名称)
                
                for 页码 in range(标签配置.get("检索页数", 1)):
                    if 页码 > 0:
                        self._货品翻页()
                        time.sleep(self.配置.默认等待秒)
                        self.页面.线程.刷新截图()
                    
                    货物区域列表 = self.辅助识别器.获取区域文字坐标(
                        self.配置.区域.商店.商店页面货物名称查询区域标签.元组
                    )
                    if 货物区域列表 is None:
                        continue
                    
                    for 货物名称, 货物配置 in 标签配置["货物"].items():
                        结果 = self._尝试购买货物(货物区域列表, 货物名称, 货物配置)
                        if  结果:
                            是否产生购买= 结果
            
            # 所有标签都处理完了，提前退出
            if len(已处理标签) >= len(self.商店购买配置):
                break
            
            # 翻页商店标签
            self._商店标签翻页()
            time.sleep(self.配置.默认等待秒)
            self.页面.线程.刷新截图()
            
            新商店标签 = self.辅助识别器.获取区域文字坐标(self.配置.区域.商店.商店标题按钮区域标签.元组)
            if 新商店标签 is None:
                break
            
            # 检查是否还有新标签可处理
            有新标签 = False
            for 标签名称 in self.商店购买配置:
                if 标签名称 not in 已处理标签:
                    if 新商店标签.find(标签名称) is not None:
                        有新标签 = True
                        break
            
            if not 有新标签:
                break
            
            商店标签 = 新商店标签

        return 是否产生购买
    def _商店标签翻页(self):
        x,y=self.配置.区域.商店.商店标题按钮区域标签.随机点(0.5)
        self.动作.drag(x,y,x-380,y)
    def _货品翻页(self):
        x,y=self.配置.区域.商店.商店页面货物名称查询区域标签.随机点(0.5)
        self.动作.drag(x,y,x,y-280)
        
    def _进入商店标签页(self, 商店标签, 标签配置: dict) -> bool:
        """点击进入商店标签页（群星/灵符等），无可购买货物则跳过"""
        
        有需要购买 = False
        for 货物配置 in 标签配置["货物"].values():
            if 货物配置["是否购买"] and not 是否为今天(货物配置["购买完成时间"]):
                有需要购买 = True
                break
        
        if not 有需要购买:
            return False
        
        标签区域 = 商店标签.find(标签配置["标签"])
        if 标签区域 is None:
            return False

        self.通用操作.点击区域(标签区域, 2)
        time.sleep(self.配置.默认等待秒)
        self.页面.线程.刷新截图()
        return True


