    def _执行强星强化(self) -> bool:
        """
        自动强星强化
        
        流程：
        1. 检测右侧卡区域是否有红点
        2. 检测是否处于自动强化模式
        3. 逐个点击有红点的装备卡
        4. 根据模式执行强化（自动/手动）
        5. 拖拽翻页继续检查
        """
        调试器.debug("强化奖励", "执行强星强化")
        
        # ========== 1. 检测红点 ==========
        右侧卡区域 = self.辅助识别器.线程.动态标签.强星页面右侧标签.强星.元组
        右侧卡扩展区域 = 缩放区域(右侧卡区域, 1.6)
        
        if not self.辅助识别器.查找图片单结果(右侧卡扩展区域, "红点1.bmp"):
            调试器.trace("强化奖励", "强星强化: 无红点，跳过")
            return True
        
        # ========== 2. 判断是否自动强化 ==========
        自动强化 = self.辅助识别器.区域包含文字(
            self.配置.区域.日常强化.自动强星按钮带红点范围区域.元组,
            "自|动"
        )
        调试器.debug("强化奖励", f"强星模式: {'自动' if 自动强化 else '手动'}")
        
        # ========== 3. 处理每个有红点的装备卡 ==========
        上部分页卡区域 = self.配置.区域.日常强化.强星上部分页卡红点范围区域
        强星按钮区域 = self.配置.区域.日常强化.强星按钮带红点范围区域
        
        for 页 in range(4):
            # 处理当前页的红点
            if not self._处理当前页红点(上部分页卡区域, 强星按钮区域, 自动强化):
                break  # 点不到红点，可能已处理完或卡住了
            
            # 检查是否还有红点
            self.页面.线程.刷新截图()
            if not self.辅助识别器.查找图片单结果(右侧卡扩展区域, "红点1.bmp"):
                调试器.debug("强化奖励", "所有红点处理完毕")
                break
            
            # 翻到下一页
            if 页 < 3:
                x, y = 上部分页卡区域.随机点(0.5)
                self.动作.drag(x, y, x - 200, y)
                time.sleep(self.配置.默认等待秒)
                self.页面.线程.刷新截图()
        
        return True


    def _处理当前页红点(self, 页卡区域, 强星按钮区域, 自动强化: bool) -> bool:
        """
        处理当前页的红点
        
        返回: True=成功处理, False=无法点击红点
        """
        for _ in range(3):
            # 点击有红点的装备卡
            if not self.页面.创建寻图偏移点击操作(
                页卡区域.元组,
                "左半红点.bmp",
                (-5, 5, 2, 25)
            ).执行():
                return False  # 点不到红点
            
            time.sleep(self.配置.默认等待秒)
            self.页面.线程.刷新截图()
            
            # 检查是否有强化红点按钮
            if not self.辅助识别器.查找图片单结果(强星按钮区域.元组, "红点1.bmp"):
                continue  # 可能只是"可升级"红点，非强化红点，继续下一个
            
            if 自动强化:
                self._自动强化(强星按钮区域)
            else:
                self._手动强化(强星按钮区域)
            
            return True
        
        return False


    def _自动强化(self, 强星按钮区域) -> None:
        """自动强化：点击自动按钮，等待完成"""
        自动按钮区域 = self.配置.区域.日常强化.自动强星按钮带红点范围区域
        
        if not self.页面.创建_通用点击区域验证文字切换(
            自动按钮区域.元组,
            自动按钮区域.元组,
            "停"
        ).执行():
            调试器.debug("强化奖励", "点击自动强化按钮失败")
            return
        
        # 等待强化完成（最多30次检查）
        for _ in range(30):
            if not self.辅助识别器.查找图片单结果(强星按钮区域.元组, "红点1.bmp"):
                调试器.debug("强化奖励", "自动强化完成")
                break
            time.sleep(self.配置.刷新等待秒)
            self.页面.线程.刷新截图()


