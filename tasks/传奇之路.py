from typing import Tuple


from core.utils import 匹配分组关键字, 提取次数
from tasks.base import 任务定义
from core.task_executors.battle_executor import 战斗任务执行器
from core.page_operations import 页面操作集
from core.debug import 调试器
import time



@任务定义(
    任务ID="chuanqizhilu",
    任务名称="传奇之路",
    任务类型="半自动任务",
    优先级=99,
    地图关键字="传奇之路|传奇之",  

    半自动任务说明="这是个半自动任务，手动开始自动结束，手动或被动进入传奇之路副本开始触发",
    半自动任务说明1="队长组队进本后会一直执行，直接到目标层数，然后退出任务，同时取消队长设置",
    半自动任务说明2="队员手动进队伍就行，被动进入副本开始任务，长时间未进入传奇副本取消任务",
    我是队长=False,
    目标层数=15,
    超过此秒数未进入副本退出任务=30,
    工作时间开始=0, 

    启用自动战斗=True,
    启用自动走位=False,
    状态_剩余次数=0,
    状态_最后在副本的时间=0,
)
class 传奇之路任务(战斗任务执行器):
    """行会试炼任务执行器"""
    
    def __init__(self, 线程, 任务配置, 任务状态):
        super().__init__(线程, 任务配置, 任务状态)       
        self.任务状态.剩余次数=0

    # 验证当前打开页面
    def 验证当前打开页面(self) -> str:
        '''
        验证当前打开页面,跨服战场多次打开存在不跳右侧标签的BUG
        返回:
        "战场" | "坐骑" | "古剑" | "组队" | "陨圣" | "其他"
        '''
        文字识别器= self.线程.文字识别器
        截图=self.线程.截图
        if 截图 is None:
            截图=self.线程.刷新截图()
        if 截图 is None:
            return "其他"
        当前页面= 文字识别器.recognize_text(截图,self.游戏配置.区域.主界面.中间页面名称区域标签.元组)
        调试器.trace("上古剑冢", f"页面识别结果: '{当前页面}'")
        if 匹配分组关键字(当前页面, "战|场") :
            return "战场"
        elif 匹配分组关键字(当前页面, "坐|骑") :
            return "坐骑"
        elif 匹配分组关键字(当前页面, "古|剑") :
            return "古剑"
        elif 匹配分组关键字(当前页面, "组|队") :
            return "组队"
        elif 匹配分组关键字(当前页面, "陨|圣") :
            return "陨圣"
        else :
            return "其他"
    # 行会试炼，这个不需要正常进入，只接受召唤进入，入口即重置    
    def 执行入口逻辑(self) -> bool:        
        # 1. 检查剩余次数
        if self.任务状态.剩余次数 <= 0:
            调试器.state(self.调试分类, f"今日次数已用完(剩余{self.任务状态.剩余次数})，跳过执行")
            return False
        if self.任务配置.我是队长:
            当前页面= self.验证当前打开页面()
            调试器.debug(self.调试分类, f"当前页面: '{当前页面}'")
            if 当前页面 != "组队":          
                # 2.1 进入跨服战场页面
                调试器.debug(self.调试分类, "步骤1: 进入跨服战场页面")
                if not self.页面.主界面操作.进入跨服战场页面():
                    调试器.error(self.调试分类, "进入跨服战场页面失败，入口逻辑中断")
                    return False
                调试器.debug(self.调试分类, "跨服战场页面进入成功")
                
                # 2.2 进入古剑页面
                调试器.debug(self.调试分类, "步骤2: 进入组队页面")
                if not self.页面.创建_通用点击区域验证文字切换(
                    self.线程.动态标签.跨服战场页面右侧标签.组队.元组,
                    self.游戏配置.区域.主界面.中间页面名称区域标签.元组,
                    "组队"
                ).执行():
                    调试器.error(self.调试分类, "进入组队页面失败，入口逻辑中断")
                    return False
                调试器.debug(self.调试分类, "组队页面进入成功")

                # 等待刷新时间，强制等待服务器时间同步
                time.sleep(max(0.5, self.游戏配置.刷新等待秒))
                self.线程.刷新截图()
                
            else:
                调试器.debug(self.调试分类, "当前已在组队页面，跳过进入步骤")
            
            层数文字=self.辅助识别器.获取区域文字(self.游戏配置.区域.传奇之路.传奇之路入口层数信息区域.元组)
            层数=0
            if not 匹配分组关键字(层数文字,"传奇|之路"):
                if not self.页面.创建_通用点击文字验证文字切换(
                    self.游戏配置.区域.传奇之路.传奇之路我的队伍按钮区域.元组,
                    "我|的",
                    self.游戏配置.区域.传奇之路.传奇之路开始挑战按钮区域.元组,
                    "开始|挑战"
                ).执行():
                    调试器.debug(self.调试分类, "进入我的队伍页面失败")
                    return False            
                层数=self.辅助识别器.获取区域次数(self.游戏配置.区域.传奇之路.传奇之路入口层数信息区域.元组)
            else:
                层数=提取次数(层数文字)
            if 层数 is None:
                调试器.debug(self.调试分类, "获取层数失败")
                return False
            
            if 层数>self.任务配置.目标层数:
                self.重置副本()
                调试器.debug(self.调试分类, f"已完成目标层数：{层数-1}")
                return False

            if not self.页面.创建_通用点击区域验证文字切换(
                self.游戏配置.区域.传奇之路.传奇之路开始挑战按钮区域.元组,           
                self.游戏配置.区域.主界面.小地图地图名显示标签.元组,
                "传奇"
            ).执行():
                调试器.debug(self.调试分类, "进入副本失败")
                return False              
            return True
        
        if time.time()-self.任务状态.最后在副本的时间>self.任务配置.超过此秒数未进入副本退出任务:
            self.重置副本()
            调试器.debug(self.调试分类, f"出副本超过30秒，默认不在执行传奇之路任务")
            return False
    def 重置副本(self):
        self.任务状态.剩余次数=0
        self.任务配置.我是队长=False
        self.线程.信号.任务启用变更.emit(self.线程.窗口名称, self.任务配置.任务ID,"我是队长" , False)
        任务定义.导出配置到JSON(self.线程.窗口名称,线程=self.线程)    
    def 执行(self) -> str:
        """
        执行任务（模板方法）
        
        子类不应继承此方法，而是重写：
        - 是否在副本中()
        - 执行入口逻辑()
        """
        调试器.info(self.调试分类, f"开始执行: {self.任务配置.任务名称}({self.任务配置.任务ID})")
        调试器.debug(self.调试分类, f"当前地图: {self.线程.当前地图}")
    
        # 1. 判断是否在副本中
        if self.是否在副本中():
            调试器.debug(self.调试分类, "判定在副本中，执行战斗逻辑")
            return self.执行副本战斗逻辑()
        
        if self.检查并处理复活():
            return "死亡"
        
       
        
        # 3. 执行入口逻辑
        调试器.debug(self.调试分类, "执行入口逻辑")
        if not self.执行入口逻辑():
             # 记录入口失败
            self.任务状态.记录入口失败()
            当前失败次数 = self.任务状态.入口连续失败次数
            冷却触发次数 = self.任务状态.入口冷却触发次数
            半程阈值 = 冷却触发次数 // 2
            
            self.通用操作.覆盖鼠标提示到边缘()
            self.通用操作.清理页面状态()  
            
            # 到达半程时执行页面清理
            if 半程阈值 > 0 and 当前失败次数 == 半程阈值:
                调试器.state(self.调试分类, f"入口连续失败{当前失败次数}次(半程)，执行页面清理")
                if self.线程.当前地图 != "盟重省":
                    调试器.debug(self.调试分类, "非主城，尝试回城")
                    self.退出副本()
            
            调试器.debug(self.调试分类, f"入口逻辑失败({当前失败次数}/{冷却触发次数})")
            
            return "失败"        
        self.通用操作.清理页面状态()
        调试器.state(self.调试分类, "已进入副本，开始战斗")
        self.任务状态.记录入口成功()
        return "进行中"
    
    # ==================== 副本战斗逻辑 ====================
    
    
    def 执行副本战斗逻辑(self) -> str:
        """
        执行副本战斗逻辑（模板方法）
        
        流程：
        1. 死亡复活 + 避让联动
        2. 更新战斗状态
        3. 位置复查（仅战斗前）
        4. 领取奖励退出
        5. 副本内检查钩子
        6. 正常阶段策略（回血）
        7. 抢怪阶段操作
        8. 退出条件检查
        9. 自动战斗/走位
        """
        调试器.debug(self.调试分类, "执行副本战斗逻辑")        
        
        #在副本就要执行
        self.任务状态.剩余次数=1
        # ========== 1. 死亡复活 + 避让联动 ==========
        if self.检查并处理复活(
        ):
            调试器.state(self.调试分类, f"死亡复活处理完成 (模式='安全复活'')")            
       
        # ========== 2. 更新战斗状态 ==========      
        self._打印战斗状态()
        
        self.任务状态.最后在副本的时间=time.time()
        
        # ========== 4. 领取奖励退出 ==========
        if self.页面.创建点击文字操作(
            self.游戏配置.区域.传奇之路.传奇之路返回按钮区域.元组,
            "返|回",
        ).执行():
            return "结束"
        
        
        if self.检查退出条件() and self.任务配置.我是队长:
            if self.辅助识别器.区域包含文字(self.游戏配置.区域.传奇之路.传奇之路通关成功提示文字区域.元组,"通关|成功"):
                调试器.state(self.调试分类, "满足退出条件")
                if self.退出副本():
                    调试器.info(self.调试分类, f"任务完成，剩余次数: {self.任务状态.剩余次数}")
                    return "完成"
                
        截图 = self.线程.截图
        self.更新目标状态()
        self.更新静止状态(截图)

    
        # ========== 9. 自动战斗/走位 ==========
       
        self.检查调整自动战斗状态()
        self.检查调整自动走位状态()
        

        return "进行中"
    
    def 检查退出条件(self) -> bool:
        """检查是否满足退出条件"""
        无目标超时 = self.公共变量.获取无目标时间() > self.无目标超时秒数
        静止超时 = self.公共变量.获取静止时长() > self.静止超时秒数
        
        调试器.debug(self.调试分类, f"退出条件检查: 无目标超时({self.无目标超时秒数}s)={无目标超时}, 静止超时({self.静止超时秒数}s)={静止超时}")
        
        return 无目标超时 and 静止超时 
        
    

    
