    def _检查并排队(self):
        """检查并排队"""
        左按钮文字 = self.辅助识别器.获取区域文字(self.游戏配置.区域.决战盟重.决战盟重页面准备按键左边按钮标签.元组) or ""
        准备匹配按钮文字 = self.辅助识别器.获取区域文字(self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组) or ""
        右按钮文字 = self.辅助识别器.获取区域文字(self.游戏配置.区域.决战盟重.决战盟重页面准备按键右边按钮标签.元组) or ""
        
        玩家是队长 = False
        if 匹配分组关键字(左按钮文字, "队长"):
            玩家是队长 = True
        if 匹配分组关键字(右按钮文字, "队长"):
            玩家是队长 = True
        
        调试器.trace(self.调试分类, f"按钮文字: 左='{左按钮文字}', 匹配='{准备匹配按钮文字}', 右='{右按钮文字}', 队长={玩家是队长}")
        
        if 准备匹配按钮文字 == "已准备":
            调试器.debug(self.调试分类, "已在准备状态")
            return True
        elif 准备匹配按钮文字 == "准备":
            调试器.debug(self.调试分类, "点击准备按钮")
            return self.页面.创建_通用点击区域验证文字切换(
                self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组,
                self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组,
                "已准备",
            ).执行()
        elif 准备匹配按钮文字 == "匹配中":
            调试器.debug(self.调试分类, "已在匹配中")
            return True
        
        # 计算已过分钟数
        分钟数 = datetime.datetime.now().minute
        if 分钟数 < 15:
            分钟数 += 60
        已过分钟数 = 分钟数 - 45
        
        调试器.debug(self.调试分类, f"已过分钟数: {已过分钟数}, 强制匹配阈值: {self.任务配置.开始几分钟以后未排队使用强制匹配}, 队长匹配阈值: {self.任务配置.开始几分钟以后队长使用匹配}")
        
        # 判断强制匹配
        if 已过分钟数 >= self.任务配置.开始几分钟以后未排队使用强制匹配:
            if 玩家是队长:
                self.任务状态.使用强制匹配 = True
                调试器.debug(self.调试分类, "队长触发强制匹配")
            else:
                if self.任务状态.剩余次数 == 5:
                    self.任务状态.使用强制匹配 = True
                    调试器.debug(self.调试分类, f"队员剩余{self.任务状态.剩余次数}次，使用强制匹配")
                
        else:
            self.任务状态.使用强制匹配 = False
            调试器.trace(self.调试分类, f"未到强制匹配时间({已过分钟数} < {self.任务配置.开始几分钟以后未排队使用强制匹配})")
        
        # 判断队长主动匹配
        开始匹配任务 = False
        if 玩家是队长 and 已过分钟数 >= self.任务配置.开始几分钟以后队长使用匹配:
            开始匹配任务 = True
            调试器.debug(self.调试分类, f"队长触发主动匹配(已过{已过分钟数}分)")
        
        if not 开始匹配任务 and not self.任务状态.使用强制匹配:
            调试器.trace(self.调试分类, f"不满足匹配条件: 队长匹配={开始匹配任务}, 强制匹配={self.任务状态.使用强制匹配}")
            return True
        
        # 统计准备人数
        准备数量 = 0
        for i in range(3):
            属性名 = f"决战盟重页面玩家准备情况标签{i + 1}"
            区域对象 = getattr(self.游戏配置.区域.决战盟重, 属性名, None)
            if 区域对象 is None:
                continue
            if self.辅助识别器.区域包含文字(区域对象.元组, "准|备"):
                准备数量 += 1
        
        调试器.debug(self.调试分类, f"准备人数: {准备数量}, 队长匹配={开始匹配任务}, 强制匹配={self.任务状态.使用强制匹配}")
        
        # 队长主动匹配
        if 玩家是队长 and 开始匹配任务:
            if 准备数量 >= 3:
                调试器.debug(self.调试分类, "队长主动匹配：人数够，点击匹配")
                return self.页面.创建_通用点击区域验证文字切换(
                    self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组,
                    self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组,
                    "匹配中",
                ).执行()
            else:
                调试器.debug(self.调试分类, f"队长主动匹配：人数不足({准备数量}<3)")
        
        # 强制匹配
        if self.任务状态.使用强制匹配:
            if 玩家是队长:
                if 准备数量 >= 3:
                    调试器.debug(self.调试分类, "队长强制匹配：人数够，点击匹配")
                    return self.页面.创建_通用点击区域验证文字切换(
                        self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组,
                        self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组,
                        "匹配中",
                    ).执行()
                else:
                    调试器.debug(self.调试分类, "队长强制匹配：人数不足，点击匹配+AI确认")
                    self.通用操作.点击区域(self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组)
                    return self.页面.创建_通用点击区域验证文字切换(
                        self.游戏配置.区域.决战盟重.决战盟重页面AI确定按钮标签.元组,
                        self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组,
                        "匹配中",
                    ).执行()
            else:
                # 队员
                if 匹配分组关键字(左按钮文字, "强制|匹配"):
                    点击区域 = self.游戏配置.区域.决战盟重.决战盟重页面准备按键左边按钮标签.元组
                elif 匹配分组关键字(右按钮文字, "强制|匹配"):
                    点击区域 = self.游戏配置.区域.决战盟重.决战盟重页面准备按键右边按钮标签.元组
                else:
                    调试器.warning(self.调试分类, "未找到强制匹配按钮")
                    return False
                
                调试器.debug(self.调试分类, f"队员强制匹配：准备人数={准备数量}")
                
                if 准备数量 >= 3:
                    return self.页面.创建_通用点击区域验证文字切换(
                        点击区域,
                        self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组,
                        "匹配中",
                    ).执行()
                else:
                    self.通用操作.点击区域(点击区域)
                    return self.页面.创建_通用点击区域验证文字切换(
                        self.游戏配置.区域.决战盟重.决战盟重页面AI确定按钮标签.元组,
                        self.游戏配置.区域.决战盟重.决战盟重页面准备匹配按钮标签.元组,
                        "匹配中",
                    ).执行()
        
        return False

